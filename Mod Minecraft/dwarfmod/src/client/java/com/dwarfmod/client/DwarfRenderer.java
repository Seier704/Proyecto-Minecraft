package com.dwarfmod.client;

import com.dwarfmod.DwarfEntity;
import com.dwarfmod.DwarfMod;
import com.geckolib.constant.DefaultAnimations;
import com.geckolib.constant.dataticket.DataTicket;
import com.geckolib.model.DefaultedEntityGeoModel;
import com.geckolib.renderer.GeoEntityRenderer;
import com.geckolib.renderer.base.BoneSnapshots;
import com.geckolib.renderer.base.RenderPassInfo;
import com.geckolib.renderer.layer.builtin.ItemInHandGeoLayer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;

/**
 * GeckoLib renderer of the dwarf: assets/dwarfmod/geckolib/{models,animations}/entity/dwarf.*.json and
 * textures/entity/dwarf.png, all generated by art/make_dwarf_geo.py. One model holds every look; the gear groups
 * that don't belong to this dwarf (role and warrior tier) are hidden here.
 */
public class DwarfRenderer extends GeoEntityRenderer<DwarfEntity, LivingEntityRenderState> {
	private static final DataTicket<Integer> ROLE = DataTicket.create("dwarfmod_role", Integer.class);
	private static final DataTicket<Integer> TIER = DataTicket.create("dwarfmod_warrior_tier", Integer.class);
	private static final String[] BONES = {"head", "body", "right_arm", "left_arm", "right_leg", "left_leg"};
	private static final String[] GEARS = {"copper", "steel", "elite"};

	public DwarfRenderer(EntityRendererProvider.Context context) {
		super(context, new DefaultedEntityGeoModel<>(DwarfMod.id("dwarf")));
		this.withRenderLayer(new ItemInHandGeoLayer<>(context, this, "right_item", "left_item"));
		// The model is 29 px tall; scaled down to the 1.4 block hitbox.
		this.withScale(0.78F);
		this.shadowRadius = 0.5F;
	}

	@Override
	public void addRenderData(DwarfEntity dwarf, Void relatedObject, LivingEntityRenderState state, float partialTick) {
		super.addRenderData(dwarf, relatedObject, state, partialTick);
		state.addGeckolibData(ROLE, dwarf.getRole());
		state.addGeckolibData(TIER, dwarf.getWarriorTier());
	}

	@Override
	public void adjustModelBonesForRender(RenderPassInfo<LivingEntityRenderState> info, BoneSnapshots snapshots) {
		super.adjustModelBonesForRender(info, snapshots);
		boolean warrior = info.getOrDefaultGeckolibData(ROLE, 0) == DwarfEntity.WARRIOR;
		int tier = info.getOrDefaultGeckolibData(TIER, 1);
		// Workers and tier 1 warriors wear copper (the first reference image), tier 2 steel, tier 3 the veteran gear.
		String gear = !warrior || tier <= 1 ? "copper" : tier == 2 ? "steel" : "elite";
		for (String bone : BONES) {
			for (String g : GEARS) {
				snapshots.ifPresent(bone + "_" + g, s -> s.skipRender(!g.equals(gear)));
			}
		}
		// Tier 2 (steel) and tier 3 (elite) bring their own red beard.
		snapshots.ifPresent("beard", s -> s.skipRender(gear.equals("elite") || gear.equals("steel")));
		snapshots.ifPresent("greataxe", s -> s.skipRender(!warrior));
		DefaultAnimations.hardcodedHeadRotation(info, snapshots, "head");
	}
}
